        public void SyncLeaveAndInout(LeaverequestCreteria employeeleavemasterCreteria)
        {
            string query = @"with leavefrominout
								as
								(
								select employeeid,attendanceon,case when afternoonabsent=true and morningabsent=true then 1 else 0.5 end inoutdays,
                                case when morningabsent then 'M' else 'E' end halfday
								from employeeinout where (afternoonabsent=true or morningabsent=true) and isactive=true
								and attendanceon >= @fromdate and attendanceon<@todate
								)

                                select employee.name,leavefrominout.*,employeeleave.id leaveid,employeeleave.days leavedays from leavefrominout
                                inner join employee on employee.id = leavefrominout.employeeid 
                                left outer join employeeleave on employeeleave.employeeid = leavefrominout.employeeid 
                                and employeeleave.fromdate=attendanceon
                                and employeeleave.isactive=true
                                where 
                                (employee.hasleft = false or employee.relievingdate>=leavefrominout.attendanceon) 
                                and (
                                employeeleave.id is null 
                                or employeeleave.days != leavefrominout.inoutdays 
                                )";
            var param = new SortedList<string, object>();
            param.Add("fromdate", employeeleavemasterCreteria.fromdate);
            param.Add("todate", employeeleavemasterCreteria.todate);
            if (employeeleavemasterCreteria.employeeid > 0)
            {
                param.Add("employeeid", employeeleavemasterCreteria.employeeid);
                query = query.Replace("and attendanceon >= @fromdate and attendanceon<@todate", "and attendanceon >= @fromdate and attendanceon<@todate and employeeid=@employeeid");
                query += " and employee.id = @employeeid";
            }
            List<LeaveInoutMissmatch> list = new List<LeaveInoutMissmatch>();
            using (var reader = ExecuteReader(query, param))
            {
                while (reader.Read())
                {
                    list.Add(new LeaveInoutMissmatch()
                    {
                        attendanceon = reader["attendanceon"] == DBNull.Value ? DateTime.MinValue : Convert.ToDateTime(reader["attendanceon"]),
                        employeeid = reader["employeeid"] == DBNull.Value ? 0 : Convert.ToInt64(reader["employeeid"]),
                        leaveid = reader["leaveid"] == DBNull.Value ? 0 : Convert.ToInt64(reader["leaveid"]),
                        inoutdays = reader["inoutdays"] == DBNull.Value ? 0 : Convert.ToDecimal(reader["inoutdays"]),
                        leavedays = reader["leavedays"] == DBNull.Value ? 0 : Convert.ToDecimal(reader["leavedays"]),
                        halfday = reader["halfday"] == DBNull.Value ? "M" : Convert.ToString(reader["halfday"]),
                    });
                }
            }

            if (list.Count > 0)
            {
                foreach (var item in list)
                {
                    bool ishalfday = item.inoutdays != Convert.ToInt32(item.inoutdays);
                    if (item.leaveid > 0)
                    {
                        var leaveitem = Search(new LeaverequestCreteria()
                        {
                            id = item.leaveid
                        }).First();
                        leaveitem.days = item.inoutdays;
                        if (ishalfday)
                            leaveitem.todatehalfday = item.halfday == "M" ? EmployeeLeave.DayMode.Morning : EmployeeLeave.DayMode.Evening;
                        leaveitem.version = -5;
                        leaveitem.sundaydays = item.attendanceon.DayOfWeek == DayOfWeek.Sunday ? item.inoutdays : 0;
                        Update(leaveitem);
                    }
                    else
                    {
                        Insert(new EmployeeLeave()
                        {
                            employeeid = item.employeeid,
                            isactive = true,
                            version = -5,
                            createdby = Context.UserID,
                            modifiedby = Context.UserID,
                            createdon = DateTimeNow,
                            modifiedon = DateTimeNow,
                            days = item.inoutdays,
                            deductsalary = true,
                            todatehalfday = !ishalfday ? EmployeeLeave.DayMode.Both : (item.halfday == "M" ? EmployeeLeave.DayMode.Morning : EmployeeLeave.DayMode.Evening),
                            sundaydays = item.attendanceon.DayOfWeek == DayOfWeek.Sunday ? item.inoutdays : 0,
                            date = item.attendanceon,
                            approvedby = Context.UserID,
                            fromdate = item.attendanceon,
                            todate = item.attendanceon,
                            reason = "Auto Synchronization"
                        });
                    }
                }
            }
        }

