            }
            List<EmployeeLeave> lst = new List<EmployeeLeave>();
            NpgsqlConnection conn = CreateConnection();
            try
            {
                conn.Open();

                NpgsqlCommand command = null;
                if (_employeeleave.id != 0)
                {
                    command = GetCommand(SQL_Search, conn);
                    command.Parameters.Add("id", NpgsqlTypes.NpgsqlDbType.Bigint).Value = _employeeleave.id;
                }
                else
                {
                    QueryBuilder qb = new QueryBuilder();
                    qb.CurrentQuery = SQL_Search.Substring(0, SQL_Search.IndexOf("where"));

                    if (!_employeeleave.includeddeleted)
                        qb.AddParameter("employeeleave.isactive", true, "=");

                    if (_employeeleave.employeeid != 0)
                    {
                        qb.AddParameter("employeeleave.employeeid", _employeeleave.employeeid, "=");
                    }
                    else
                    {
                        if (!string.IsNullOrEmpty(_employeeleave.employeecode))
                        {
                            qb.AddParameter("employee.employeecode", _employeeleave.employeecode, "=");
                        }
                        else
                        {
                            if (_employeeleave.companyid > 0)
                                qb.AddParameter("employee.companyid", _employeeleave.companyid, "=");

                            if (_employeeleave.departmentid > 0)
                                qb.AddParameter("employee.departmentid", _employeeleave.departmentid, "=");

