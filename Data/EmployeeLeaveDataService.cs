        private void CreateInOut(DirectLeaveChange item)
        {

            EmployeeinoutDataService eds = new EmployeeinoutDataService() { Context = this.Context };
            var rows = eds.Search(new EmployeeinoutCreteria()
            {
                employeeid = item.employeeid,
                fromdate = item.date,
                showinactive = true
            });
            NpgsqlTransaction transaction = null;
            try
            {
                using (NpgsqlConnection conn = CreateConnection())
                {
                    conn.Open();
                    transaction = conn.BeginTransaction();
                    item.success = true;
                    if (rows.Count == 0)
                    {
                        var workinghours = eds.DefaultWorkingHourse(item.employeeid);
                        Employeeinout einout = new Employeeinout();
                        einout.attendanceon = item.date;
                        einout.intime = (int)workinghours.Item3.TotalMinutes;
                        einout.outtime = (int)workinghours.Item4.TotalMinutes;
                        einout.employeeid = item.employeeid;
                        einout.isactive = true;
                        einout.createdby = Context.UserID;
                        einout.modifiedby = Context.UserID;
                        einout.createdon = DateTimeNow;
                        einout.modifiedon = DateTimeNow;
                        einout.morningabsent = item.status == "A" || item.status == "1H";
                        einout.afternoonabsent = item.status == "A" || item.status == "2H";
                        eds.Insert(transaction, conn, einout, 1);
                    }
                    else if (rows.Count == 1)
                    {
                        var workinghours = eds.DefaultWorkingHourse(item.employeeid);
                        rows[0].morningabsent = item.status == "A" || item.status == "1H";
                        rows[0].afternoonabsent = item.status == "A" || item.status == "2H";
                        rows[0].isactive = true;
                        //rows[0].intime = (int)workinghours.Item1.TotalMinutes;
                        //rows[0].outtime = (int)workinghours.Item2.TotalMinutes;
                        eds.Update(transaction, conn, rows[0]);
                    }
                    else if (rows.Count > 1 && rows.Exists(x => x.isactive == true))
                    {
                        var row = rows.Find(x => x.isactive == true);
                        var workinghours = eds.DefaultWorkingHourse(item.employeeid);
                        row.morningabsent = item.status == "A" || item.status == "1H";
                        row.afternoonabsent = item.status == "A" || item.status == "2H";
                        row.isactive = true;
                        //rows[0].intime = (int)workinghours.Item1.TotalMinutes;
                        //rows[0].outtime = (int)workinghours.Item2.TotalMis;
                        eds.Update(transaction, conn, row);
                    }
                    else if(rows.Count >0)
                    {
                        var workinghours = eds.DefaultWorkingHourse(item.employeeid);
                        rows[0].morningabsent = item.status == "A" || item.status == "1H";
                        rows[0].afternoonabsent = item.status == "A" || item.status == "2H";
                        rows[0].isactive = true;
                        //rows[0].intime = (int)workinghours.Item1.TotalMinutes;
                        //rows[0].outtime = (int)workinghours.Item2.TotalMinutes;
                        eds.Update(transaction, conn, rows[0]);
                    }
                    else
                    {
                        item.success = false;
                    }
                    transaction.Commit();
                    conn.Close();
                }
            }
            catch (Exception exp)
            {
                WebAPI.Common.Logger.Instance(Context.OrganizationID).Log(exp, WebAPI.Common.Logger.LogType.Error, item);
                throw exp;
            }
        }

        public EmployeeLeave Insert(EmployeeLeave oLeaverequest)
        {

            NpgsqlTransaction transaction = null;
            try
            {
                using (NpgsqlConnection conn = CreateConnection())
                {
                    conn.Open();
                    transaction = conn.BeginTransaction();

                    Insert(transaction, conn, oLeaverequest, false);


                    transaction.Commit();
                    conn.Close();
                }
            }
            catch (Exception exp)
            {
                if (exp.Message.Contains("emplyee_leave_unique_constraint"))
                {
                    var searchresult = Search(new LeaverequestCreteria()
                    {
                        date = oLeaverequest.date.Date,
                        employeeid = oLeaverequest.employeeid,
                        includeddeleted = true
                    });
                    if (searchresult.Count > 0)
                    {
                        foreach (var item in searchresult)
                        {
                            var param = new SortedList<string, object>();
                            param.Add("id", item.id);
                            param.Add("version", item.version);
                            ExecuteQuery(SQL_Delete, param);
                        }
                        return Insert(oLeaverequest);
                    }
                }
                WebAPI.Common.Logger.Instance(Context.OrganizationID).Log(exp, WebAPI.Common.Logger.LogType.Error, oLeaverequest);
                throw exp;
            }

            return oLeaverequest;
        }

        private void UpdateDays(EmployeeLeave oLeaverequest)
        {
            var days = (decimal)oLeaverequest.todate.Subtract(oLeaverequest.fromdate).TotalDays + 1;



            oLeaverequest.sundaydays = 0;
            if (oLeaverequest.fromdate == oLeaverequest.todate)
            {
                if (oLeaverequest.todatehalfday != EmployeeLeave.DayMode.Both)
                    days = (decimal)0.5;
                else if (oLeaverequest.fromdatehalfday != EmployeeLeave.DayMode.Both)
                    days = (decimal)0.5;
                else
                    days = 1;

                if (oLeaverequest.fromdate.DayOfWeek == DayOfWeek.Sunday)
                    oLeaverequest.sundaydays = days;
            }
            else
            {
                if (oLeaverequest.todatehalfday != EmployeeLeave.DayMode.Both)
                    days -= (decimal)0.5;
                if (oLeaverequest.fromdatehalfday != EmployeeLeave.DayMode.Both)
                    days -= (decimal)0.5;

                for (DateTime dt = oLeaverequest.fromdate; dt <= oLeaverequest.todate; dt = dt.AddDays(1))
                {
                    if (dt.DayOfWeek == DayOfWeek.Sunday)
                    {
                        if (dt == oLeaverequest.fromdate)
                        {
                            if (oLeaverequest.fromdatehalfday != EmployeeLeave.DayMode.Both)
                                oLeaverequest.sundaydays += (decimal)0.5;
                            else
                                oLeaverequest.sundaydays += (decimal)1;
                        }
                        else if (dt == oLeaverequest.todate)
                        {
                            if (oLeaverequest.todatehalfday != EmployeeLeave.DayMode.Both)
                                oLeaverequest.sundaydays += (decimal)0.5;
                            else
                                oLeaverequest.sundaydays += (decimal)1;
                        }
                    }
                }
            }
            if (oLeaverequest.status != "OD")

                oLeaverequest.days = (decimal)days;

        }
