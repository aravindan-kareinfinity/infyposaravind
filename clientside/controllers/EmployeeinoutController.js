        $scope.toMinute = function (value) {

            var hour = 0;
            var minute = 0;
            var newvalue = value.toLowerCase().replace(' ', '').replace('am', '').replace('pm', '');
            var hourmin = newvalue.split(':');
            if (hourmin.length == 2) {
                minute = parseInt(hourmin[1]);
            }
            var hour = parseInt(hourmin[0]);
            if (value.toLowerCase().indexOf('pm') > 0)
                hour += 12;
            return (hour * 60) + minute;
            return -1;
        };

        $scope.toTime = function (minute) {
            var imin = parseInt(minute);
            var remmin = imin % 60;
            var hour = (imin - remmin) / 60;
            if (hour < 12)
                return (hour < 10 ? '0' : '') + hour + (remmin < 10 ? ':0' : ':') + remmin + ' AM';
            else {
                hour -= 12;
                return (hour < 10 ? '0' : '') + hour + (remmin < 10 ? ':0' : ':') + remmin + ' PM';
            }
        };

