                if ($scope.validmode != 5 && $scope.validmode != 6) {
                    $scope.ShowResult(result);
                }
                else if ($scope.validmode == 5) {
                    $scope.ShowAbsenties(result);
                }
                else {
                    $scope.ShowSummary(result);
                }

